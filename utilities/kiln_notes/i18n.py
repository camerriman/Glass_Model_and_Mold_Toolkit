def normalize_language(language: str | None) -> str:
    if language in LANGUAGE_OPTIONS:
        return language
    return DEFAULT_LANGUAGE


def locale_for_language(language: str | None) -> str:
    normalized = normalize_language(language)
    return LOCALE_BY_LANGUAGE.get(normalized, DEFAULT_LOCALE)


def normalize_locale(locale: str | None) -> str:
    if locale in SUPPORTED_LOCALES:
        return locale
    return DEFAULT_LOCALE


def date_display_format(locale: str | None = None) -> str:
    normalized_locale = normalize_locale(locale)
    if normalized_locale == "en-US":
        return "MM/DD/YYYY"
    return "YYYY/MM/DD"


def format_localized_date(value: date, locale: str | None = None) -> str:
    normalized_locale = normalize_locale(locale)
    if normalized_locale == "en-US":
        return value.strftime("%m/%d/%Y")
    return value.strftime("%Y/%m/%d")


def format_localized_time(value: datetime | time, locale: str | None = None) -> str:
    normalized_locale = normalize_locale(locale)
    time_value = value.time() if isinstance(value, datetime) else value

    if normalized_locale == "en-US":
        return time_value.strftime("%I:%M %p").lstrip("0")
    return time_value.strftime("%H:%M")


def format_localized_datetime(value: datetime, locale: str | None = None) -> str:
    normalized_locale = normalize_locale(locale)
    date_text = format_localized_date(value.date(), normalized_locale)
    time_text = format_localized_time(value, normalized_locale)
    return f"{date_text} {time_text}"


def language_label(language: str | None, display_language: str | None = None) -> str:
    _ = display_language
    normalized = normalize_language(language)
    return LANGUAGE_OPTIONS.get(normalized, LANGUAGE_OPTIONS[DEFAULT_LANGUAGE])


def translate(key: str, language: str | None = None, **kwargs: Any) -> str:
    normalized = normalize_language(language)
    template = TRANSLATIONS.get(normalized, {}).get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return template.format(**kwargs)
    except (KeyError, ValueError):
        return template
